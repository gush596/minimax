// FP16 reciprocal unit datapath (quadratic minimax interpolation).
//
//   x    = 1 + frac/1024,  frac = { seg[D1-1:0], t[10-D1-1:0] }  (FP16 fraction)
//   P(t) = C0 + t * (m2*t - 1024*m1) * 2^-(D2+20)
//        = C0 + C1*t + C2*t^2,  C1 = -m1*2^-(D2+10), C2 = m2*2^-(D2+20)
//   (inner = m2*t - 1024*m1 is <= 0: the C1 term is a subtraction.)
//
// Runtime operations only: ROM read, two small integer multiplies,
// power-of-2 shifts (pure wiring), one subtract, one add, one rounding
// shift. No floating-point arithmetic anywhere.
//
// C0 is carried as m0 = C0*2^11 (12-bit integer, 1024..2048): outputs
// live in (0.5,1] so the FP16 exponent field is always -1 and y*2^11 IS
// the significand.
// y_q11 = y*2^11 in [1024,2048]; fp16_out packs it as FP16.
//
// ROM: one entry per segment, packed {m2, m1, m0}, generated by gen_rom.py
// from the coefficient CSV of ../results/.
//
// Latency: 4 cycles, in-order. Parameters default to the main config
// d1=3, d2=7 (8 segments, t 7 bit, m1/m2 7 bit).
//
// Assumption (checked by tb_fp16_recip and datapath_model.py): with the
// shipped ROM, inner = m2*t - 1024*m1 is always <= 0 and y in (0.5,1].

module fp16_recip #(
    parameter D1      = 3,
    parameter D2      = 7,
    parameter ROMFILE = "rom_d1_3_d2_7.memh"
)(
    input  wire        clk,
    input  wire        rst_n,
    input  wire        in_valid,
    input  wire [9:0]  frac,      // FP16 fraction of x in [1,2)
    output reg         out_valid,
    output reg  [11:0] y_q11,     // y * 2^11, 1024..2048
    output reg  [15:0] fp16_out   // packed FP16 result in (0.5,1]
);

    localparam T_W   = 10 - D1;      // fraction bits inside a segment (t width)
    localparam P_W   = D2 + T_W;     // m2 * t product width
    localparam IW    = D2 + 12;      // inner = m1*1024 - m2*t, with headroom
    localparam CW    = IW + T_W + 1; // core = t * inner
    localparam SHIFT = D2 + 9;       // 2^-(D2+20) -> 2^-11 output scale

    reg [12 + 2*D2 - 1:0] rom [0:(1 << D1) - 1];
    initial $readmemh(ROMFILE, rom);

    // ---- stage 0: split frac, register -------------------------------
    reg [T_W-1:0] s0_t;
    reg [D1-1:0]  s0_seg;
    reg           s0_v;
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            s0_v <= 1'b0;
        end else begin
            s0_t   <= frac[T_W-1:0];
            s0_seg <= frac[9 -: D1];
            s0_v   <= in_valid;
        end
    end

    // ---- stage 1: synchronous ROM read -------------------------------
    reg [12 + 2*D2 - 1:0] s1_rom;
    reg [T_W-1:0]         s1_t;
    reg                   s1_v;
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            s1_v <= 1'b0;
        end else begin
            s1_rom <= rom[s0_seg];
            s1_t   <= s0_t;
            s1_v   <= s0_v;
        end
    end

    // ---- stage 2: first multiply (m2*t), subtract --------------------
    wire [11:0]   m0 = s1_rom[11:0];
    wire [D2-1:0] m1 = s1_rom[12 +: D2];
    wire [D2-1:0] m2 = s1_rom[12 + D2 +: D2];

    wire [P_W-1:0]        p     = m2 * s1_t;
    wire signed [IW-1:0]  inner = $signed({{(IW - P_W){1'b0}}, p})
                                - $signed({{(IW - D2 - 10){1'b0}}, m1, 10'd0});

    reg [11:0]        s2_m0;
    reg [T_W-1:0]     s2_t;
    reg signed [IW-1:0] s2_inner;
    reg               s2_v;
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            s2_v <= 1'b0;
        end else begin
            s2_m0   <= m0;
            s2_t    <= s1_t;
            s2_inner <= inner;
            s2_v    <= s1_v;
        end
    end

    // ---- stage 3: second multiply (t*inner), add m0<<SHIFT, round -----
    wire signed [CW-1:0] core = s2_inner * $signed({1'b0, s2_t});
    wire signed [31:0]   acc  = ($signed({20'd0, s2_m0}) <<< SHIFT) + core;
    wire signed [31:0]   acc_r = acc + $signed(32'd1 <<< (SHIFT - 1)); // round to nearest
    wire [11:0]          y_next = acc_r >>> SHIFT;                     // y * 2^11

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            out_valid <= 1'b0;
        end else begin
            out_valid <= s2_v;
            if (s2_v) begin
                y_q11   <= y_next;
                fp16_out <= (y_next >= 12'd2048) ? 16'h3c00        // 1.0
                                                 : {5'b01110, y_next[9:0]};
            end
        end
    end

endmodule
